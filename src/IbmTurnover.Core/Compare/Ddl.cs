using System.Text;
using IbmTurnover.Core.Models;

namespace IbmTurnover.Core.Compare;

/// <summary>Renders Db2 for i DDL from catalog definitions, qualified with the given library.</summary>
public static class Ddl
{
    /// <summary>Qualified SQL name; each part is quoted when it is not a plain identifier.</summary>
    public static string Q(string lib, string name) => $"{SqlText.Id(lib)}.{SqlText.Id(name)}";

    /// <summary>SQL column / constraint name.</summary>
    public static string C(string name) => SqlText.Id(name);

    public static string ColumnSpec(ColumnDef c, bool forCreate = true)
    {
        var sb = new StringBuilder();
        sb.Append(C(c.Name));
        if (!string.IsNullOrEmpty(c.SystemName) && !c.SystemName.Equals(c.Name, StringComparison.OrdinalIgnoreCase))
            sb.Append(" FOR COLUMN ").Append(SqlText.ClName(c.SystemName));
        sb.Append(' ').Append(c.TypeSignature);
        if (c.Ccsid is not null) sb.Append(" CCSID ").Append(c.Ccsid);
        if (c.IsIdentity && forCreate) sb.Append(" GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1)");
        if (!c.Nullable) sb.Append(" NOT NULL");
        if (c.Default is not null) sb.Append(" DEFAULT ").Append(c.Default);
        return sb.ToString();
    }

    public static string CreateTable(string lib, TableDef t)
    {
        var sb = new StringBuilder();
        sb.Append("CREATE TABLE ").Append(Q(lib, t.Name));
        if (!string.IsNullOrEmpty(t.SystemName) && !t.SystemName.Equals(t.Name, StringComparison.OrdinalIgnoreCase))
            sb.Append(" FOR SYSTEM NAME ").Append(SqlText.ClName(t.SystemName));
        sb.AppendLine(" (");
        var lines = t.Columns.OrderBy(c => c.Ordinal).Select(c => "  " + ColumnSpec(c)).ToList();
        if (t.PrimaryKey.Count > 0)
            lines.Add($"  CONSTRAINT {C(t.PrimaryKeyName ?? t.Name + "_PK")} PRIMARY KEY ({Cols(t.PrimaryKey)})");
        foreach (var uk in t.UniqueKeys) lines.Add($"  UNIQUE ({Cols(uk)})");
        foreach (var ck in t.Checks) lines.Add($"  CONSTRAINT {C(ck.Name)} CHECK ({ck.Clause})");
        sb.AppendLine(string.Join(",\n", lines));
        sb.Append(')');
        return sb.ToString();
    }

    public static string Cols(IEnumerable<string> names) => string.Join(", ", names.Select(C));

    public static string CreateIndex(string lib, IndexDef i) =>
        $"CREATE {(i.UniqueWhereNotNull ? "UNIQUE WHERE NOT NULL " : i.IsUnique ? "UNIQUE " : "")}INDEX {Q(lib, i.Name)}" +
        (string.IsNullOrEmpty(i.SystemName) || i.SystemName.Equals(i.Name, StringComparison.OrdinalIgnoreCase) ? "" : $" FOR SYSTEM NAME {SqlText.ClName(i.SystemName)}") +
        $" ON {Q(lib, i.Table)} ({string.Join(", ", i.Columns.Select(c => C(c.Name) + (c.Descending ? " DESC" : "")))})";

    public static string AddForeignKey(string lib, ForeignKeyDef fk, string refLib) =>
        $"ALTER TABLE {Q(lib, fk.Table)} ADD CONSTRAINT {Q(lib, fk.Name)} FOREIGN KEY ({Cols(fk.Columns)})" +
        $" REFERENCES {Q(refLib, fk.RefTable)} ({Cols(fk.RefColumns)}) ON DELETE {Rule(fk.DeleteRule)} ON UPDATE {Rule(fk.UpdateRule)}";

    /// <summary>Only the five rules Db2 knows; a catalog value is never pasted into DDL unchecked.</summary>
    public static string Rule(string rule) => rule.Trim().ToUpperInvariant().Replace('_', ' ') switch
    {
        "CASCADE" => "CASCADE", "SET NULL" => "SET NULL", "SET DEFAULT" => "SET DEFAULT", "NO ACTION" => "NO ACTION", "RESTRICT" => "RESTRICT",
        var other => throw new TurnoverException($"Unknown referential rule '{other}'."),
    };

    public static string DropConstraint(string lib, string table, string name) =>
        $"ALTER TABLE {Q(lib, table)} DROP CONSTRAINT {Q(lib, name)}";

    public static string CreateSequence(string lib, SequenceDef s, long start) =>
        $"CREATE SEQUENCE {Q(lib, s.Name)} AS {s.DataType} START WITH {start} INCREMENT BY {s.Increment}" +
        (s.MinValue is null ? "" : $" MINVALUE {s.MinValue}") +
        (s.MaxValue is null ? "" : $" MAXVALUE {s.MaxValue}") +
        (s.Cache <= 1 ? " NO CACHE" : $" CACHE {s.Cache}") + (s.Cycle ? " CYCLE" : " NO CYCLE");

    public static string AlterSequenceAttributes(string lib, SequenceDef s) =>
        $"ALTER SEQUENCE {Q(lib, s.Name)} INCREMENT BY {s.Increment}" +
        (s.MinValue is null ? " NO MINVALUE" : $" MINVALUE {s.MinValue}") +
        (s.MaxValue is null ? " NO MAXVALUE" : $" MAXVALUE {s.MaxValue}") +
        (s.Cache <= 1 ? " NO CACHE" : $" CACHE {s.Cache}") + (s.Cycle ? " CYCLE" : " NO CYCLE");

    public static string Describe(SequenceDef s, string lib) =>
        CreateSequence(lib, s, s.Start) + (s.NextValue is null ? "" : $"\n-- next value in this environment: {s.NextValue}");

    public static string CreateDataQueue(string lib, DataQueueDef q) =>
        $"CRTDTAQ DTAQ({SqlText.ClName(lib)}/{SqlText.ClName(q.Name)}) MAXLEN({q.MaxLength}) SEQ({q.Sequence})" +
        (q.Sequence.Equals("*KEYED", StringComparison.OrdinalIgnoreCase) ? $" KEYLEN({q.KeyLength})" : "") +
        $" SENDERID({(q.IncludeSenderId ? "*YES" : "*NO")}) TEXT({SqlText.ClText(q.Text)})";

    public static string DataAreaValue(DataAreaDef a, string? value) => a.Type.ToUpperInvariant() switch
    {
        "*DEC" => decimal.TryParse(value, System.Globalization.NumberStyles.Number, System.Globalization.CultureInfo.InvariantCulture, out var d)
            ? d.ToString(System.Globalization.CultureInfo.InvariantCulture) : "0",
        "*LGL" => value == "1" ? "'1'" : "'0'",
        _ => SqlText.ClText(value),
    };

    public static string CreateDataArea(string lib, DataAreaDef a, string? value) =>
        $"CRTDTAARA DTAARA({SqlText.ClName(lib)}/{SqlText.ClName(a.Name)}) TYPE({a.Type}) LEN({a.Length}{(a.Type.Equals("*DEC", StringComparison.OrdinalIgnoreCase) ? " " + a.Decimals : "")})" +
        $" VALUE({DataAreaValue(a, value)}) TEXT({SqlText.ClText(a.Text)})";

    public static string ChangeDataArea(string lib, DataAreaDef a, string? value) =>
        $"CHGDTAARA DTAARA({SqlText.ClName(lib)}/{SqlText.ClName(a.Name)}) VALUE({DataAreaValue(a, value)})";

    public static string JobDescription(string verb, string lib, JobDescriptionDef j) =>
        $"{verb} JOBD({SqlText.ClName(lib)}/{SqlText.ClName(j.Name)}) INLLIBL({(j.LibraryList.Count == 0 ? "*NONE" : string.Join(" ", j.LibraryList.Select(SqlText.ClName)))})" +
        $" USER({SqlText.ClName(j.User)})" + (string.IsNullOrEmpty(j.JobQueue) ? "" : $" JOBQ({QualifiedCl(j.JobQueue)})") + $" TEXT({SqlText.ClText(j.Text)})";

    public static string Message(string verb, string lib, MessageDef m) =>
        $"{verb} MSGID({SqlText.ClName(m.Id)}) MSGF({SqlText.ClName(lib)}/{SqlText.ClName(m.File)}) MSG({SqlText.ClText(m.Text)})" +
        (string.IsNullOrEmpty(m.SecondLevel) ? "" : $" SECLVL({SqlText.ClText(m.SecondLevel)})") + $" SEV({Math.Clamp(m.Severity, 0, 99)})";

    public static string Profile(string verb, UserProfileDef u) =>
        $"{verb} USRPRF({SqlText.ClName(u.Name)}){(verb == "CRTUSRPRF" ? " PASSWORD(*NONE)" : "")} USRCLS({u.UserClass})" +
        $" SPCAUT({(u.SpecialAuthorities.Count == 0 ? "*NONE" : string.Join(" ", u.SpecialAuthorities.Select(SqlText.ClName)))})" +
        $" GRPPRF({SqlText.ClName(u.GroupProfile)}) SUPGRPPRF({(u.SupplementalGroups.Count == 0 ? "*NONE" : string.Join(" ", u.SupplementalGroups.Select(SqlText.ClName)))})" +
        $" CURLIB({SqlText.ClName(u.CurrentLibrary)}) INLPGM({QualifiedCl(u.InitialProgram)}) INLMNU({QualifiedCl(u.InitialMenu)})" +
        $" LMTCPB({u.LimitCapabilities}) JOBD({QualifiedCl(u.JobDescription)}) TEXT({SqlText.ClText(u.Text)})";

    /// <summary>LIB/OBJ, *SPECIAL or OBJ — each part validated.</summary>
    public static string QualifiedCl(string value)
    {
        var parts = value.Split('/');
        return string.Join("/", parts.Select(SqlText.ClName));
    }

    public static string Label(string target, string? text, bool columnText = false) =>
        $"LABEL ON {target} {(columnText ? "TEXT IS" : "IS")} {SqlText.Literal(text ?? "")}";

    public static string Describe(ProgramObject p, string lib) =>
        $"{lib}/{p.Name} {p.ObjectType} {p.Attribute}\n" +
        $"source   : {p.SourceLibrary}/{p.SourceFile}({p.SourceMember})\n" +
        $"src hash : {p.SourceHash}\n" +
        $"src chg  : {p.SourceChanged:yyyy-MM-dd HH:mm}\n" +
        $"compiled : {p.Created:yyyy-MM-dd HH:mm}\n" +
        $"binds    : {(p.BoundServicePrograms.Count == 0 ? "-" : string.Join(", ", p.BoundServicePrograms))}\n" +
        $"files    : {(p.FileReferences.Count == 0 ? "-" : string.Join(", ", p.FileReferences.Select(f => $"{f.Library}/{f.File}")))}";

    /// <summary>CL command run through QSYS2.QCMDEXC, so the whole turnover is one SQL script.</summary>
    public static string Qcmdexc(string cl) => $"CALL QSYS2.QCMDEXC({SqlText.Literal(cl)})";

    /// <summary>
    /// CL to build the object from source. Several commands are separated by new lines. DDS display, printer and
    /// logical files have no REPLACE(*YES), so an existing one is deleted first (after the backup step); a DDS physical
    /// file is changed in place with CHGPF so its data is kept.
    /// </summary>
    /// <summary>True when <see cref="CompileCommand"/> knows how to build this object type and language.</summary>
    public static bool CanBuild(ProgramObject p) =>
        TurnoverOptions.IsValidLibraryName(p.Name) && TurnoverOptions.IsValidLibraryName(string.IsNullOrEmpty(p.SourceFile) ? "X" : p.SourceFile)
        && Builds.Commands(p, "LIB", "SRCLIB", true, x => x, x => x) is not null;

    public static string? CompileCommand(ProgramObject p, string pgmLib, string srcLib, bool exists = true, string? commandProgram = null)
    {
        var name = SqlText.ClName(p.Name);
        var lib = SqlText.ClName(pgmLib);
        var src = $"SRCFILE({SqlText.ClName(srcLib)}/{SqlText.ClName(p.SourceFile)}) SRCMBR({SqlText.ClName(string.IsNullOrEmpty(p.SourceMember) ? p.Name : p.SourceMember)})";
        var dlt = exists ? $"DLTF FILE({lib}/{name})\n" : "";
        return (p.ObjectType.ToUpperInvariant(), p.Attribute.ToUpperInvariant()) switch
        {
            ("*FILE", "PF") => exists ? $"CHGPF FILE({lib}/{name}) {src}" : $"CRTPF FILE({lib}/{name}) {src}",
            ("*FILE", "LF") => $"{dlt}CRTLF FILE({lib}/{name}) {src}",
            ("*FILE", "PRTF") => $"{dlt}CRTPRTF FILE({lib}/{name}) {src}",
            ("*FILE", "DSPF") => $"{dlt}CRTDSPF FILE({lib}/{name}) {src}",
            ("*CMD", _) => $"CRTCMD CMD({lib}/{name}) PGM({commandProgram ?? "*LIBL/" + name}) {src} REPLACE(*YES)",
            ("*PNLGRP", _) => $"CRTPNLGRP PNLGRP({lib}/{name}) {src} REPLACE(*YES)",
            ("*MENU", "UIM") => $"CRTMNU MENU({lib}/{name}) TYPE(*UIM) {src} REPLACE(*YES)",   // DSPF / PGM menus need their display file or program: by hand
            ("*PGM", "CLP") => $"CRTCLPGM PGM({lib}/{name}) {src} REPLACE(*YES)",
            ("*PGM", "RPG" or "RPG38") => $"CRTRPGPGM PGM({lib}/{name}) {src} REPLACE(*YES)",
            ("*PGM", "CBLLE") => $"CRTBNDCBL PGM({lib}/{name}) {src} REPLACE(*YES)",
            ("*PGM", "SQLCBLLE") => $"CRTSQLCBLI OBJ({lib}/{name}) {src} OBJTYPE(*PGM) COMMIT(*NONE) REPLACE(*YES)",
            ("*PGM", "CLE") => $"CRTBNDC PGM({lib}/{name}) {src} REPLACE(*YES)",
            ("*PGM", "SQLC") => $"CRTSQLCI OBJ({lib}/{name}) {src} OBJTYPE(*PGM) COMMIT(*NONE) REPLACE(*YES)",
            ("*SRVPGM", "SQLRPGLE") => $"CRTSQLRPGI OBJ({pgmLib}/{p.Name}) {src} OBJTYPE(*SRVPGM) COMMIT(*NONE) REPLACE(*YES)",
            ("*SRVPGM", "RPGLE") => $"CRTRPGMOD MODULE(QTEMP/{p.Name}) {src} REPLACE(*YES)\n" +
                              $"CRTSRVPGM SRVPGM({pgmLib}/{p.Name}) MODULE(QTEMP/{p.Name}) EXPORT(*SRCFILE) SRCFILE({srcLib}/QSRVSRC) SRCMBR({p.Name}) REPLACE(*YES)",
            ("*PGM", "SQLRPGLE") => $"CRTSQLRPGI OBJ({pgmLib}/{p.Name}) {src} OBJTYPE(*PGM) COMMIT(*NONE) REPLACE(*YES)",
            ("*PGM", "CLLE") => $"CRTBNDCL PGM({pgmLib}/{p.Name}) {src} REPLACE(*YES)",
            ("*PGM", "RPGLE") => $"CRTBNDRPG PGM({pgmLib}/{p.Name}) {src} REPLACE(*YES)",
            // Anything else (other languages, multi-language service programs) is built by hand: a guessed compiler would fail.
            _ => null,
        };
    }
}

public enum TypeChange { Same, Widening, Narrowing, Incompatible, SemanticChange }

public static class TypeCompat
{
    private static readonly string[] IntRank = ["SMALLINT", "INTEGER", "BIGINT"];
    private static readonly HashSet<string> Chars = new(StringComparer.OrdinalIgnoreCase) { "CHAR", "VARCHAR", "CHARACTER", "GRAPHIC", "VARGRAPHIC", "NCHAR", "NVARCHAR", "CLOB", "BINARY", "VARBINARY" };
    private static readonly HashSet<string> Decimals = new(StringComparer.OrdinalIgnoreCase) { "DECIMAL", "NUMERIC", "DEC" };

    /// <summary>What happens to existing TARGET data when its column becomes the SOURCE definition.</summary>
    public static TypeChange Classify(ColumnDef from, ColumnDef to)
    {
        if (from.TypeSignature == to.TypeSignature) return TypeChange.Same;
        string f = Norm(from.DataType), t = Norm(to.DataType);

        if (Chars.Contains(f) && Chars.Contains(t))
        {
            if ((to.Length ?? 0) < (from.Length ?? 0)) return TypeChange.Narrowing;
            return f == t ? TypeChange.Widening : TypeChange.SemanticChange; // CHAR<->VARCHAR changes trailing-blank behaviour
        }
        if (Decimals.Contains(f) && Decimals.Contains(t))
        {
            int fi = (from.Length ?? 0) - (from.Scale ?? 0), ti = (to.Length ?? 0) - (to.Scale ?? 0);
            if (ti < fi || (to.Scale ?? 0) < (from.Scale ?? 0)) return TypeChange.Narrowing;
            return TypeChange.Widening;
        }
        // Same type, different precision: TIMESTAMP(6) → TIMESTAMP(12), DECFLOAT(16) → DECFLOAT(34).
        if (f == t && f is "TIMESTAMP" or "DECFLOAT")
        {
            int fp = from.Length ?? (f == "TIMESTAMP" ? 6 : 34), tp = to.Length ?? (t == "TIMESTAMP" ? 6 : 34);
            return tp >= fp ? TypeChange.Widening : TypeChange.Narrowing;
        }
        int fr = Array.IndexOf(IntRank, f), tr = Array.IndexOf(IntRank, t);
        if (fr >= 0 && tr >= 0) return tr < fr ? TypeChange.Narrowing : TypeChange.Widening;
        if (fr >= 0 && Decimals.Contains(t))
            return (to.Length ?? 0) - (to.Scale ?? 0) >= new[] { 5, 10, 19 }[fr] ? TypeChange.Widening : TypeChange.Narrowing;
        return TypeChange.Incompatible;
    }

    private static string Norm(string t) => t.ToUpperInvariant() switch { "INT" => "INTEGER", "DEC" => "DECIMAL", "CHARACTER" => "CHAR", var x => x };

    /// <summary>SELECT COUNT(*) that finds rows the new definition cannot hold. Null when no meaningful check exists.</summary>
    public static string? TruncationCheck(string lib, string table, ColumnDef from, ColumnDef to)
    {
        string t = Norm(to.DataType), col = Ddl.C(from.Name), q = Ddl.Q(lib, table);
        if (Chars.Contains(t) && to.Length is int len)
            return $"SELECT COUNT(*) FROM {q} WHERE LENGTH(RTRIM({col})) > {len}";
        if (Decimals.Contains(t) && to.Length is int p)
        {
            var s = to.Scale ?? 0;
            var limit = "1" + new string('0', Math.Max(p - s, 0));
            return $"SELECT COUNT(*) FROM {q} WHERE ABS({col}) >= {limit} OR {col} <> ROUND({col}, {s})";
        }
        return t switch
        {
            "SMALLINT" => $"SELECT COUNT(*) FROM {q} WHERE {col} NOT BETWEEN -32768 AND 32767",
            "INTEGER" => $"SELECT COUNT(*) FROM {q} WHERE {col} NOT BETWEEN -2147483648 AND 2147483647",
            _ => null,
        };
    }
}
